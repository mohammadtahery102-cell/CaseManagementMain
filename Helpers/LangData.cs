        internal static Dictionary<string, string> Build(string code)
        {
            var map = new Dictionary<string, string>(StringComparer.Ordinal);
            int column = ColumnFor(code);
            if (column < 0) return map;

            foreach (string[] row in Rows)
            {
                if (row.Length <= column) continue;
                string value = row[column];
                if (!string.IsNullOrEmpty(value)) map[row[0]] = value;
            }
            return map;
        }

        // ترتیبِ ستون‌ها در جدولِ زیر: 0=فارسی(کلید) 1=پشتو 2=عربی 3=اردو 4=انگلیسی
        private static int ColumnFor(string code)
        {
            switch (code)
            {
                case Lang.Pashto:  return 1;
                case Lang.Arabic:  return 2;
                case Lang.Urdu:    return 3;
                case Lang.English: return 4;
                default:           return -1;   // فارسی ترجمه لازم ندارد
            }
        }

