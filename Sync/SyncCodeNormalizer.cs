using System.Text;

namespace CaseManagement.Sync
{
    // ─────────────────────────────────────────────────────────────────────────
    // رفعِ اشکالِ گزارش‌شده: «کد در HTML هست، عکس هست، رکورد دیتابیس هست، ولی
    // همگام‌سازی رد می‌کند». علتِ رایج: کدِ اختصاصی (PublicCode/Code) در یک
    // منبع با ارقامِ فارسی/عربی نوشته شده یا فاصله‌ی اضافه دارد، در حالی که
    // منبعِ دیگر (مثلاً نامِ فایلِ عکس) با ارقامِ لاتین و بدون فاصله است — از
    // نظرِ دیتابیس دو مقدارِ کاملاً متفاوت، هرچند برای چشمِ انسان یکی‌اند.
    //
    // این کلاس فقط برای «مقایسه/تطبیق» استفاده می‌شود؛ مقدارِ خام (که در
    // پیام‌ها نشان داده می‌شود یا برای رکوردِ تازه ذخیره می‌شود) دست‌نخورده
    // می‌ماند — نه معماریِ همگام‌سازی و نه مقادیرِ ذخیره‌شده تغییر می‌کنند.
    // ─────────────────────────────────────────────────────────────────────────
    public static class SyncCodeNormalizer
    {
        public static string Normalize(string code)
        {
            if (string.IsNullOrWhiteSpace(code)) return "";

            var sb = new StringBuilder(code.Length);
            foreach (char c in code)
            {
                if (c == '‌' /* نیم‌فاصله */ || char.IsWhiteSpace(c))
                    continue; // فاصله‌ها (ابتدا/انتها/میانی) کاملاً نادیده گرفته می‌شوند

                // آموزش — رفعِ باگِ واقعی («کد در HTML هست ولی تطبیق رد می‌کند»،
                // با آزمونِ واقعی بازتولید و تأیید شد): فایل‌های HTML خروجیِ
                // Excel/Word اغلب دورِ رقم‌های فارسی/RTL نشانه‌های *نامرئیِ*
                // جهت‌دهیِ دوسویه می‌گذارند — LRM (U+200E)، RLM (U+200F)، ALM
                // (U+061C)، ZWSP (U+200B)، BOM (U+FEFF). این کاراکترها نه رقم‌اند
                // نه IsWhiteSpace (دستهٔ یونیکدِ Format، نه Space)، پس نه با کدِ
                // بالا حذف می‌شدند و نه در پیام خطا یا چشمِ کاربر دیده می‌شوند —
                // کدِ «۲۰۹۹» با این نشانه‌ها برای انسان دقیقاً «2099» به‌نظر
                // می‌رسد ولی به‌عنوان کلیدِ دیکشنری با «2099» خالص یکی نیست.
                if (char.GetUnicodeCategory(c) == System.Globalization.UnicodeCategory.Format)
                    continue;

                if (c >= '۰' && c <= '۹')       // ارقامِ فارسی
                    sb.Append((char)('0' + (c - '۰')));
                else if (c >= '٠' && c <= '٩')  // ارقامِ عربی
                    sb.Append((char)('0' + (c - '٠')));
                else
                    sb.Append(c);
            }

            return sb.ToString();
        }
    }
}
